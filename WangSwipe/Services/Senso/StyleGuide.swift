/// The style guide the app files into Senso for the stylist to search.
/// Edit it here; the app files the new version the next time the Agent tab opens.
enum StyleGuide {
    static let text = """
    WangSwipe men's style guide

    Building an outfit
    An outfit in WangSwipe is one top (shirt, sweater or jacket) and one bottom (pants or jeans). \
    Start from the piece with the most character, then pick the other to support it rather than compete. \
    One statement piece per outfit is enough: a loud jacket wants quiet pants, and bold pants want a plain top.

    Color
    Navy, grey, black, white, cream, olive, tan and brown all go with each other, so two neutrals are always safe. \
    Pair one color with neutrals rather than two strong colors together. \
    Tonal outfits (shades of one color, like brown on tan or grey on charcoal) look deliberate and expensive. \
    Black and brown can be worn together when the textures differ, such as black denim with a brown leather jacket. \
    Darker on the bottom and lighter on top is the classic balance; reversing it reads more fashion-forward.

    Proportion and fit
    Balance volume: a boxy or cropped top sits best over straight or slightly wide pants; a slim top over relaxed pants \
    gives a modern shape; avoid baggy on both halves unless the look is intentionally oversized streetwear. \
    Jackets should end at the hip or above for most body types; cropped jackets lengthen the legs. \
    Pants should touch the shoe with little or no break for slim cuts; wide cuts can pool slightly. \
    Shoulder seams should sit at the edge of the shoulder.

    Texture and materials
    Mixing textures adds depth to a plain palette: leather with denim, knit with cotton twill, waxed or coated denim with soft wool. \
    Coated or waxed jeans read dressier than washed denim and pair well with leather and knitwear. \
    Technical fabrics and puffers pair best with simple denim or cargo pants.

    Occasions
    Smart casual: a knit or overshirt with dark, clean jeans or chinos. \
    Night out: dark tones, one luxe texture (leather, suede, coated denim). \
    Weekend: relaxed denim, a sweatshirt or overshirt, sneakers. \
    Cold weather: layer a knit under a shell or leather jacket; keep the pants simple.

    Finishing the look
    Shoes: white leather sneakers go with almost any casual outfit; Chelsea boots dress up dark denim; \
    chunky boots balance wide or heavy pants. Match belt and shoe leather when both show. \
    Keep accessories to one or two: a watch, a simple chain or a cap.

    Body and photo advice
    Speak to fit, color and proportion only. Never rate someone's face, body or attractiveness. \
    For a shorter frame, cropped jackets and a single color from top to bottom add height. \
    For a broader frame, structured jackets and straight-leg pants keep lines clean.
    """
}
